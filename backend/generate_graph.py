# ヘルパー
# ---------------------------------------------------------------
_stations: dict[str, str] = {}  # id -> 名称
_lines: list[dict] = []
_edges: list[dict] = []


def s(sid: str, name: str) -> str:
    if sid not in _stations:
        _stations[sid] = name
    return sid


def line(lid: str, name: str) -> None:
    """路線を登録する。同一IDの重複登録は無視（先勝ち）。

    路線ID（路線記号）はJR西日本公式に準拠しており、A（東海道・山陽・北陸本線系）や
    H（JR東西線・学研都市線）のように複数の愛称路線が同一IDを共有する。
    フロントは lineId→名前 の辞書を作るため、IDごとに1エントリだけ登録し、
    名前には共有する愛称をすべて含める。
    """
    if any(l["id"] == lid for l in _lines):
        return
    _lines.append({"id": lid, "name": name})


def seq(stations: list[tuple[str, str, float, int]], lid: str) -> None:
    """隣接駅ペアのエッジを登録する。
    stations: [(id, name, distance_to_next, time_to_next), ...]
    最後の要素の distance/time は無視される（次の駅がないため）。
    """
    for i, (sid, sname, dist, t) in enumerate(stations):
        s(sid, sname)
        if i < len(stations) - 1:
            nid, nname, _, _ = stations[i + 1]
            s(nid, nname)
            _edges.append({
                "fromStationId": sid,
                "toStationId": nid,
                "lineId": lid,
                "distance": dist,
                "travelTime": t,
            })


